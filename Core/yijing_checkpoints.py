# 全局检查点索引（384 项）
# ═══════════════════════════════════════════════════════════════

def build_checkpoint_database() -> List[Checkpoint]:
    """构建完整的 384 项检查点数据库"""
    checkpoints = []
    counter = 1

    for domain_key, domain_name in DOMAINS.items():
        subdomains = SUBDOMAINS.get(domain_key, [])
        for sub_idx, sub_name in enumerate(subdomains):
            templates = CHECKPOINT_TEMPLATES.get(sub_name, [])
            for cp_idx, (name, desc, is_strong, weight, thresh_type, thresh_val) in enumerate(templates):
                cp_id = f"{domain_key}{sub_idx+1:02d}C{cp_idx+1:02d}"
                checkpoints.append(Checkpoint(
                    id=cp_id,
                    domain=domain_key,
                    domain_name=domain_name,
                    subdomain=sub_name,
                    name=name,
                    description=desc,
                    is_strong=is_strong,
                    default_weight=weight,
                    threshold_type=thresh_type,
                    threshold_value=thresh_val,
                    unit="",  # 动态获取
                ))
                counter += 1

    return checkpoints


def get_checkpoint_by_id(cp_id: str) -> Checkpoint:
    """按 ID 查找检查点"""
    all_cps = build_checkpoint_database()
    for cp in all_cps:
        if cp.id == cp_id:
            return cp
    return None


def get_checkpoints_by_domain(domain: str) -> List[Checkpoint]:
    """按领域获取检查点"""
    all_cps = build_checkpoint_database()
    return [cp for cp in all_cps if cp.domain == domain]


def get_checkpoints_by_subdomain(domain: str, subdomain: str) -> List[Checkpoint]:
    """按子领域获取检查点"""
    all_cps = build_checkpoint_database()
    return [cp for cp in all_cps if cp.domain == domain and cp.subdomain == subdomain]


def get_strong_checkpoints() -> List[Checkpoint]:
    """获取所有强关联检查点"""
    all_cps = build_checkpoint_database()
    return [cp for cp in all_cps if cp.is_strong]


def get_weak_checkpoints() -> List[Checkpoint]:
    """获取所有弱关联检查点"""
    all_cps = build_checkpoint_database()
    return [cp for cp in all_cps if not cp.is_strong]


