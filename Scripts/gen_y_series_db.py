def build_catalog():
    """构建完整型谱数据库"""
    catalog = []
    for (model, power_kw, speed_rpm, frame_size, poles,
         stator_od, stator_id, core_length) in RAW_DATA:

        # 转矩: T = 9550 * P / n  (Nm)
        torque_nm = round(9550.0 * power_kw / speed_rpm, 2)

        # 长径比: lambda = L / D
        lambda_ratio = round(core_length / stator_id, 3)

        # D²L: (D/1000)^2 * (L/1000)  (m³)
        d_m = stator_id / 1000.0
        l_m = core_length / 1000.0
        d_squared_l = round(d_m ** 2 * l_m, 6)

        # 气隙估算 (mm): 外径越大, 气隙略大
        air_gap = round(0.30 + (stator_od - 120) * 0.0015, 2)

        # 轭厚估算 (mm): (OD - ID) / 2 - 槽高(约65% of (OD-ID)/2)
        slot_depth = round((stator_od - stator_id) / 2 * 0.60, 1)
        yoke_thickness = round((stator_od - stator_id) / 2 - slot_depth, 1)

        # 槽配合 (定子槽/转子槽) - Y系列标准
        slot_map = {
            2: {(120, 67): (18, 16), (130, 72): (18, 16), (155, 84): (24, 20),
                (175, 98): (30, 26), (210, 116): (30, 26), (260, 150): (36, 28),
                (290, 165): (36, 28), (327, 187): (36, 28), (368, 210): (36, 28),
                (400, 225): (42, 34), (445, 255): (42, 34)},
            4: {(120, 75): (24, 22), (130, 80): (24, 22), (155, 98): (36, 28),
                (175, 110): (36, 28), (210, 136): (36, 28), (260, 170): (36, 28),
                (290, 187): (48, 44), (327, 210): (48, 44), (368, 245): (48, 44),
                (400, 260): (60, 50), (445, 300): (60, 50)},
            6: {(130, 86): (36, 28), (155, 106): (36, 28), (175, 120): (36, 28),
                (210, 148): (36, 28), (260, 182): (36, 28), (290, 205): (54, 44),
                (327, 230): (54, 44), (368, 260): (72, 58), (400, 285): (72, 58),
                (445, 325): (72, 58)},
            8: {(210, 148): (48, 44), (260, 182): (48, 44), (290, 205): (54, 44),
                (327, 230): (54, 44), (368, 260): (72, 58), (400, 285): (72, 58),
                (445, 325): (72, 58)},
        }
        slots_s, slots_r = slot_map.get(poles, {}).get(
            (stator_od, stator_id), (36, 28))

        entry = {
            "model": model,
            "power_kw": power_kw,
            "speed_rpm": speed_rpm,
            "torque_nm": torque_nm,
            "poles": poles,
            "sync_speed_rpm": {2: 3000, 4: 1500, 6: 1000, 8: 750}[poles],
            "frame_size": frame_size,
            "cooling": "IC411 (自扇冷却)",
            "protection_class": "IP44",
            "stator_od_mm": stator_od,
            "stator_inner_dia_mm": stator_id,
            "core_length_mm": core_length,
            "air_gap_mm": air_gap,
            "lambda": lambda_ratio,
            "d_squared_l_m3": d_squared_l,
            "slots_stator": slots_s,
            "slots_rotor": slots_r,
            "yoke_thickness_mm": yoke_thickness,
            "efficiency_ie": "IE2",
            "insulation_class": "F",
        }
        catalog.append(entry)
    return catalog


def main():
    catalog = build_catalog()

    # 按极数分组统计
    by_poles = {}
    for e in catalog:
        p = e["poles"]
        by_poles.setdefault(p, []).append(e)

    output = {
        "_meta": {
            "name": "Y系列三相异步电动机型谱物理数据库",
            "standard": "GB/T 28575 / Y系列型谱",
            "data_source": "电机设计手册(陈世坤) + Y系列型谱标准",
            "formulas": {
                "torque": "T = 9550 * P / n  (P:kW, n:rpm, T:Nm)",
                "lambda": "lambda = L / D  (L:铁心长度, D:定子内径)",
                "d_squared_l": "D2L = (D/1000)^2 * (L/1000)  (m^3)"
            },
            "series": "Y (基本系列, IP44, IC411)",
            "frame_range": "80 ~ 280",
            "power_range_kw": "0.55 ~ 90",
            "poles_available": [2, 4, 6, 8],
            "total_models": len(catalog),
            "models_by_poles": {str(k): len(v) for k, v in sorted(by_poles.items())},
            "note": "本数据库作为Motor-AI分层类比选型法的基石, "
                    "用于型谱查表模式和类比推算的参考基准。"
                   "D(定子内径)和L(铁心长度)是D2L物理内核的核心变量。"
        },
        "catalog": catalog,
        "by_poles": {str(k): v for k, v in sorted(by_poles.items())},
    }

    out_path = os.path.join(os.path.dirname(__file__), "y_series_physics.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(output, f, ensure_ascii=False, indent=2)

    print(f"OK: {len(catalog)} models written to {out_path}")
    print(f"  2-pole: {len(by_poles.get(2, []))} models")
    print(f"  4-pole: {len(by_poles.get(4, []))} models")
    print(f"  6-pole: {len(by_poles.get(6, []))} models")
    print(f"  8-pole: {len(by_poles.get(8, []))} models")

    # 验证抽样
    for m in ["Y801-2", "Y160M-4", "Y280M-8"]:
        e = next(x for x in catalog if x["model"] == m)
        print(f"  {m}: T={e['torque_nm']}Nm, D={e['stator_inner_dia_mm']}mm, "
              f"L={e['core_length_mm']}mm, lambda={e['lambda']}, "
              f"D2L={e['d_squared_l_m3']}m3")


if __name__ == "__main__":
    main()
